#!/usr/bin/env node
/**
 * Folds the built JS and CSS into one self-contained workspace/workplane.html.
 *
 * Why a single file: the Bahulam local service authorises every request with a
 * `?token=` parameter or an `x-bahulam-local-token` header. A panel is loaded
 * with that token in its URL, but a relative `<script src="./x.js">` does not
 * inherit it, so external assets return 401. Inlining removes the sub-requests
 * entirely — the same reason the plugin's original panel is one file.
 */
import { readFileSync, writeFileSync, rmSync, existsSync } from "node:fs";
import { join } from "node:path";

const BUILD = "workspace/.wp-build";
const OUT = "workspace/workplane.html";

const js = readFileSync(join(BUILD, "bundle.js"), "utf8");
const cssPath = join(BUILD, "bundle.css");
const css = existsSync(cssPath) ? readFileSync(cssPath, "utf8") : "";

// `</script>` inside the bundle would terminate the host <script> element early.
const safeJs = js.replace(/<\/script>/gi, "<\\/script>");

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Azure Cost · Workplane</title>
    <!-- Generated by scripts/inline.mjs. Edit workplane-src/, then npm run build. -->
    <style>
      body { margin: 0; background: #f4f5f7; font-family: system-ui, sans-serif; }
      @media (prefers-color-scheme: dark) { body { background: #0f1115; } }
      .shell { max-width: 1180px; margin: 0 auto; padding: 16px 14px 48px; }
      .boot { padding: 48px; text-align: center; color: #5b6270; font-size: 14px; }
${css}
    </style>
  </head>
  <body>
    <div id="workplane-root"><p class="boot">Loading workplane…</p></div>
    <script type="module">
${safeJs}
    </script>
  </body>
</html>
`;

writeFileSync(OUT, html);
rmSync(BUILD, { recursive: true, force: true });

const kb = (n) => `${(n / 1024).toFixed(0)} KB`;
console.log(`${OUT}  ${kb(Buffer.byteLength(html))}  (js ${kb(js.length)}, css ${kb(css.length)})`);
console.log("Self-contained: no external asset requests, so no token is needed for sub-resources.");
